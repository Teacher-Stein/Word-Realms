// ---------------------------------------------------------------------------
// Game state: persistence, party, roster, per-student stats, leaderboard,
// run lifecycle. Everything is stored in this browser (classroom computer).
// Data is shaped so it can later be pushed to a shared backend unchanged.
// ---------------------------------------------------------------------------


function defaultState() {
  return {
    unlockedRealms: CONFIG.DEFAULT_UNLOCKED.slice(),
    teacherAutoUnlock: false,
    soundOn: true,
    ember: 0,              // meta-currency, survives a party wipe
    permanentPerks: [],    // legacy; migrated into realmPerks below
    realmPerks: {},        // realmId -> [perkId] — perks are per REALM now
    roster: null,          // { className, students:[name,...] }
    studentStats: {},      // name -> { correct, wrong, monsters, damage, relics, teamups }
    leaderboard: [],       // completed run records
    perksEnabled: true,    // teacher can switch the Forge off for a class
    coachOn: true,         // in-game explanations, first time only
    coachSeen: {},
    shortRealm: false,     // a 9-layer map for a single period
    run: null,
  };
}

let STATE = loadState();

function loadState() {
  try {
    const raw = localStorage.getItem(CONFIG.SAVE_KEY);
    if (!raw) return defaultState();
    const st = Object.assign(defaultState(), JSON.parse(raw));
    migratePerks(st);
    migrateRun(st);
    return st;
  } catch (e) {
    console.warn("save load failed, starting fresh", e);
    return defaultState();
  }
}

// A run saved by an older version won't have the newer fields. Fill them in
// rather than wiping a class's progress in the middle of a lesson.
// v5.5: perks used to be one flat list that applied to every realm forever.
// Anything a class already bought is honoured, but only in Realm 1 - from
// Realm 2 on, each unit starts its own climb.
function migratePerks(st) {
  st.realmPerks = st.realmPerks || {};
  if (Array.isArray(st.permanentPerks) && st.permanentPerks.length &&
      !st.realmPerks[1]) {
    st.realmPerks[1] = st.permanentPerks.slice();
  }
}

function migrateRun(st) {
  const r = st.run;
  if (!r) return;
  if (!Array.isArray(r.potions)) r.potions = [];
  if (!r.shopStock)              r.shopStock = {};
  // v5.7 added a gear row; stock generated by an older version has none
  Object.values(r.shopStock).forEach(stock => {
    if (stock && !Array.isArray(stock.gear)) stock.gear = [];
  });
  if (!Array.isArray(r.relics))  r.relics = [];
  if (!Array.isArray(r.absent))  r.absent = [];
  if (typeof r.shieldActive  !== "boolean") r.shieldActive  = false;
  if (typeof r.clarityActive !== "boolean") r.clarityActive = false;
  if (typeof r.usedLastStand  !== "boolean") r.usedLastStand  = false;
  if (typeof r.usedLastBreath !== "boolean") r.usedLastBreath = false;
  if (typeof r.usedEcho       !== "boolean") r.usedEcho       = false;
  // v5.8 events
  if (!Array.isArray(r.missedQs))   r.missedQs   = [];
  if (!Array.isArray(r.eventsSeen)) r.eventsSeen = [];
  if (typeof r.idolTaken     !== "boolean") r.idolTaken     = false;
  if (typeof r.longRoadTaken !== "boolean") r.longRoadTaken = false;
  // v5.7: Last Stands became a counter so the relic and the perk can stack.
  if (typeof r.lastStandsUsed !== "number") {
    r.lastStandsUsed = (r.usedLastStand ? 1 : 0) + (r.usedLastBreath ? 1 : 0);
  }
  // v5.3: Momentum is gone. Old saves carry momentum/moRouse/moGuard - they
  // are simply ignored rather than migrated, since nothing reads them now.
  if (typeof r.stake          !== "string")  r.stake          = "safe";
  if (typeof r.focusUsed      !== "boolean") r.focusUsed      = false;
  if (typeof r.focusArmed     !== "boolean") r.focusArmed     = false;
  if (typeof r.teamUpsUsed    !== "number")  r.teamUpsUsed    = 0;
  if (!r.stats) r.stats = { correct: 0, wrong: 0, monsters: 0, teamups: 0 };
  // Older maps contain no shop rooms - harmless, they just won't appear
  // until the next run.
}

function saveState() {
  try {
    localStorage.setItem(CONFIG.SAVE_KEY, JSON.stringify(STATE));
  } catch (e) {
    console.warn("save failed", e);
  }
}

function factoryReset() {
  STATE = defaultState();
  saveState();
}

// Start of a new term with the same class: keep who is in the room, throw
// away everything they earned. Between this and Factory Reset there is now a
// reset for every situation a teacher actually has.
function newTermReset() {
  const roster = STATE.roster;
  STATE = defaultState();
  STATE.roster = roster;
  if (roster) roster.students.forEach(ensureStudentStats);
  saveState();
}

// A leaver or a transfer. Previously the only way to remove one name was to
// wipe the whole save.
function removeStudent(name) {
  if (!STATE.roster) return;
  STATE.roster.students = STATE.roster.students.filter(n => n !== name);
  delete STATE.studentStats[name];
  const run = STATE.run;
  if (run) {
    run.turnQueue = (run.turnQueue || []).filter(n => n !== name);
    run.absent = (run.absent || []).filter(n => n !== name);
    if (run.currentStudent === name) nextStudent();
  }
  saveState();
}

