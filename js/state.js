function damage(n = 1) {
  const run = STATE.run;
  if (!run) return { blocked: false, dead: false };

  if (run.shieldActive) {                       // Storm Shield potion
    run.shieldActive = false;
    saveState();
    return { blocked: true, blockedBy: "Storm Shield", dead: false };
  }
  if (!run.usedLuckyCharm && hasRelic("lucky_charm")) {
    run.usedLuckyCharm = true;
    saveState();
    return { blocked: true, blockedBy: "Lucky Charm", dead: false };
  }

  // Shields soak damage before hearts are touched.
  let absorbed = 0;
  if (run.shields > 0) {
    absorbed = Math.min(run.shields, n);
    run.shields -= absorbed;
    n -= absorbed;
  }
  run.hearts = Math.max(0, run.hearts - n);
  saveState();
  return {
    blocked: n === 0 && absorbed > 0,
    blockedBy: absorbed > 0 ? "Shields" : null,
    absorbed, dealt: n,
    dead: run.hearts <= 0,
  };
}

// ---------------------------- shields / gear -------------------------------
function addShields(n) {
  STATE.run.shields = Math.min(99, (STATE.run.shields || 0) + n);
  saveState();
}

// Shields are topped up at a REST POINT only - a Rest room or a Safe Path -
// never on walking into an ordinary room. Free full armour every room was why
// armour felt weightless; now it is a resource the class has to manage.
function refillShields() {
  const run = STATE.run;
  if (!run) return 0;
  let gain = CONFIG.REST_SHIELDS || 0;
  const armour = run.armour ? gearById(run.armour) : null;
  if (armour) {
    if (armour.id === "windwarden")   gain += 3;
    if (armour.id === "aegis_mantle") gain += 5;
  }
  if (run.enchants && run.enchants.armour === "ward_etch") gain += 2;
  if (hasRelic("aegis_charm")) gain += 2;
  if (hasRelic("storm_crown")) gain += 3;
  if (hasPerk("warded")) gain += 2;
  // top up to the full figure rather than stacking on what's left, so a
  // rest is always worth the same and never snowballs
  const before = run.shields || 0;
  run.shields = Math.max(before, gain);
  saveState();
  return Math.max(0, run.shields - before);
}

// Potions and shop patch kits add shields on top of whatever is left.
function addShieldTop(n) {
  const run = STATE.run;
  if (!run) return 0;
  run.shields = Math.min(99, (run.shields || 0) + n);
  saveState();
  return n;
}

function equipGear(gear) {
  const run = STATE.run;
  const slot = gear.slot;
  const previous = run[slot];
  run[slot] = gear.id;
  if (previous !== gear.id) run.enchants[slot] = null;   // etching is lost
  saveState();
  return previous ? gearById(previous) : null;
}

function availableGear(slot = null) {
  const run = STATE.run;
  let pool = ALL_GEAR.filter(g => g.id !== run.weapon && g.id !== run.armour);
  if (slot) pool = pool.filter(g => g.slot === slot);
  return pool.length ? pick(pool) : null;
}

function applyEnchant(slot, enchantId) {
  STATE.run.enchants[slot] = enchantId;
  saveState();
}

// ---------------------------- streaks --------------------------------------
function bumpStreak() {
  const run = STATE.run;
  run.streak = (run.streak || 0) + 1;
  run.bestStreak = Math.max(run.bestStreak || 0, run.streak);
  saveState();
  return run.streak;
}
function resetStreak() {
  if (STATE.run) { STATE.run.streak = 0; saveState(); }
}

function heal(n = 1) {
  const run = STATE.run;
  if (!run) return;
  run.hearts = Math.min(run.maxHearts, run.hearts + n);
  saveState();
}

function addShards(n) {
  const run = STATE.run;
  let mult = run.shardMultiplier || 1;
  if (hasRelic("coin_purse")) mult += 0.25;
  const gained = Math.max(1, Math.round(n * mult));
  run.shards += gained;
  saveState();
  return gained;
}
function addEmber(n)  { STATE.ember += n; saveState(); }

function hasRelic(id) {
  return !!(STATE.run && STATE.run.relics.some(r => r.id === id));
}

function addRelic(relic) {
  STATE.run.relics.push(relic);
  if (relic.id === "storm_crown") {
    STATE.run.maxHearts += 1;
    STATE.run.hearts = Math.min(STATE.run.maxHearts, STATE.run.hearts + 1);
  }
  if (relic.id === "second_wind") {
    STATE.run.maxHearts += 1;
    STATE.run.hearts = Math.min(STATE.run.maxHearts, STATE.run.hearts + 1);
  }
  saveState();
}

// A relic the party doesn't already hold. `rarities` narrows the pool.
// Relic rarity used to be consumed by exactly one thing: the shop price.
// Drops themselves were uniform, so Giant-Slayer - an epic that halves every
// elite fight - was exactly as likely as a common, and one elite kill in nine
// handed a class a fight-halving relic. Rarity now weights the roll, which is
// what makes an epic a moment rather than a coin flip.
// Tuned against the actual pool (7 common, 7 uncommon, 3 rare, 3 epic) rather
// than picked as round numbers. A first pass at 50/30/15/5 put epics at 2.5%
// of drops - roughly one epic every twenty runs, which is not "you earned it",
// it is a lottery. At 50/30/25/15 an epic is 6.6% of drops, so about one run
// in nine contains one. Rare enough to be a moment, common enough to be a goal.
const RARITY_WEIGHT = { common: 50, uncommon: 30, rare: 25, epic: 15 };

function availableRelic(rarities = null) {
  const owned = STATE.run.relics.map(r => r.id);
  let pool = RELICS.filter(r => !owned.includes(r.id));
  if (rarities) {
    const narrowed = pool.filter(r => rarities.includes(r.rarity));
    if (narrowed.length) pool = narrowed;
  }
  if (!pool.length) return null;

  const total = pool.reduce((n, r) => n + (RARITY_WEIGHT[r.rarity] || 10), 0);
  let roll = Math.random() * total;
  for (const r of pool) {
    roll -= (RARITY_WEIGHT[r.rarity] || 10);
    if (roll <= 0) return r;
  }
  return pool[pool.length - 1];
}

// --------------------------- potions ---------------------------------------
// Capped. A run was picking up 8.5 potions - 6.5 of them from streak bonuses
// alone - so the party ended every realm holding six unopened bottles, the
// shop's potion row was worthless and the Deep Pack perk bought nothing.
// Returns false when the pack is full, so callers can say so instead of
// silently swallowing the reward.
function addPotion(id) {
  const run = STATE.run;
  if (!run) return false;
  const cap = CONFIG.MAX_POTIONS || 99;
  if (run.potions.length >= cap) return false;
  run.potions.push(id);
  saveState();
  return true;
}

function consumePotion(id) {
  const i = STATE.run.potions.indexOf(id);
  if (i === -1) return false;
  STATE.run.potions.splice(i, 1);
  saveState();
  return true;
}

// --------------------------- shop ------------------------------------------
// Stock is generated once per shop node and remembered, so re-entering or
// resuming the lesson shows the same wares.
function shopStockFor(nodeId) {
  const run = STATE.run;
  if (run.shopStock[nodeId]) return run.shopStock[nodeId];
  const owned = run.relics.map(r => r.id);
  const pool = shuffle(RELICS.filter(r => !owned.includes(r.id)));
  const relicPicks = [];
  // one better-than-common relic where possible, plus one of anything
  const fancy = pool.find(r => r.rarity !== "common");
  if (fancy) relicPicks.push(fancy);
  pool.forEach(r => {
    if (relicPicks.length < 2 && !relicPicks.includes(r)) relicPicks.push(r);
  });
  // GEAR. Until v5.7 the shop stocked relics and potions only, and the ONLY
  // other source was a 50% roll on an elite kill - 0.58 offers per whole run.
  // Six pieces of gear existed that a class could go an entire realm without
  // ever being shown. A gear row also gives late shards somewhere to go, which
  // is the other half of the surplus problem.
  const gearPool = shuffle(ALL_GEAR.filter(g =>
    g.id !== run.weapon && g.id !== run.armour));
  const gearPick = gearPool[0];

  const stock = {
    relics: relicPicks.map(r => ({ id: r.id, price: relicPrice(r), sold: false })),
    gear: gearPick
      ? [{ id: gearPick.id, price: GEAR_PRICE[gearPick.rarity] || 45, sold: false }]
      : [],
    potions: shuffle(POTIONS).slice(0, 3)
      .map(p => ({ id: p.id, price: p.price, sold: false })),
  };
  run.shopStock[nodeId] = stock;
  saveState();
  return stock;
}

function buyFromShop(nodeId, kind, index) {
  const run = STATE.run;
  const stock = run.shopStock[nodeId];
  if (!stock) return { ok: false, reason: "no stock" };
  const entry = stock[kind][index];
  if (!entry || entry.sold) return { ok: false, reason: "sold" };
  if (run.shards < entry.price) return { ok: false, reason: "poor" };
  run.shards -= entry.price;
  entry.sold = true;
  if (kind === "relics") addRelic(relicById(entry.id));
  else if (kind === "gear") equipGear(gearById(entry.id));
  else addPotion(entry.id);
  saveState();
  return { ok: true, item: itemById(entry.id), kind };
}

