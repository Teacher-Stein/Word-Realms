function runScore() {
  const run = STATE.run;
  const minutes = Math.max(1, Math.round((Date.now() - run.startedAt) / 60000));
  const accuracy = run.stats.correct + run.stats.wrong > 0
    ? run.stats.correct / (run.stats.correct + run.stats.wrong) : 0;
  // shards + surviving hearts + accuracy, with only a light time factor so
  // classes aren't punished for discussing answers properly
  return Math.round(
    run.shards * 10 +
    run.hearts * 25 +
    accuracy * 200 +
    Math.max(0, 60 - minutes) * 2
  );
}

function clearRealm() {
  const run = STATE.run;
  const realmId = run.realmId;
  const score = runScore();
  const minutes = Math.max(1, Math.round((Date.now() - run.startedAt) / 60000));
  let emberGained = Math.round(run.shards / 2) + 5;
  if (run.relics.some(r => r.id === "ember_pouch")) {
    emberGained = Math.round(emberGained * 1.5);
  }
  addEmber(emberGained);

  STATE.leaderboard.push({
    className: STATE.roster ? STATE.roster.className : "Unnamed class",
    partyName: STATE.roster ? (STATE.roster.partyName || "") : "",
    heroId: run.heroId,
    bestStreak: run.bestStreak || 0,
    realmId,
    score,
    minutes,
    hearts: run.hearts,
    maxHearts: run.maxHearts,
    shards: run.shards,
    correct: run.stats.correct,
    wrong: run.stats.wrong,
    monsters: run.stats.monsters,
    date: new Date().toISOString().slice(0, 10),
  });
  STATE.leaderboard.sort((a, b) => b.score - a.score);
  STATE.leaderboard = STATE.leaderboard.slice(0, 50);

  if (STATE.teacherAutoUnlock && REALMS[realmId + 1] &&
      !STATE.unlockedRealms.includes(realmId + 1)) {
    STATE.unlockedRealms.push(realmId + 1);
  }
  const nextUnlocked = STATE.unlockedRealms.includes(realmId + 1);
  STATE.run = null;
  saveState();
  return { emberGained, score, minutes, nextUnlocked };
}

// Party wipe.
//
// This used to roll 50/50 between banking Ember and "keeping one relic". Two
// things were wrong with that:
//
//   1. The relic branch did NOTHING. It returned the relic's name, the results
//      screen printed it, and STATE.run was nulled two lines later. There was
//      no field anywhere that could hold it. So HALF of all wipes paid the
//      class absolutely nothing - and because the roll only happened when the
//      party was carrying relics, holding relics HALVED your expected reward
//      for dying.
//
//   2. Death paid `run.shards` undivided while victory paid `shards / 2`, so
//      losing was worth roughly twice as much Ember as winning. A class that
//      wanted Forge perks was better off farming the map and throwing the boss
//      fight. Ten-year-olds find that by accident and then on purpose.
//
// Dying now always pays, and always pays strictly less than winning.
function handleRunDeath() {
  const run = STATE.run;
  const gained = Math.round(run.shards / 3) + run.relics.length * 2 + 2;
  addEmber(gained);
  const outcome = { type: "ember", amount: gained };
  STATE.run = null;
  saveState();
  return outcome;
}

function teacherUnlock(realmId, unlocked) {
  if (unlocked && !STATE.unlockedRealms.includes(realmId)) {
    STATE.unlockedRealms.push(realmId);
  } else if (!unlocked) {
    STATE.unlockedRealms = STATE.unlockedRealms.filter(r => r !== realmId);
  }
  saveState();
}
