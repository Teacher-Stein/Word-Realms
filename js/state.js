function startNewRun(realmId, heroId) {
  const realm = REALMS[realmId];
  const map = generateMap(realm);
  // the per-realm ramp: one fewer starting heart every fourth realm
  const rampHearts = Math.floor((realmId - 1) /
    ((CONFIG.REALM_RAMP && CONFIG.REALM_RAMP.heartsPer) || 99));
  let hearts = Math.max(5, CONFIG.START_HEARTS - rampHearts);
  if (typeof hasPerk === "function" && hasPerk("second_wind")) hearts += 1;

  STATE.run = {
    realmId,
    heroId,
    map,
    currentNodeId: map.nodes[0].id,
    visitedNodeIds: [map.nodes[0].id],
    hearts,
    maxHearts: Math.max(CONFIG.START_HEARTS, hearts),
    shards: 0,
    relics: [],
    potions: [],          // consumable ids held by the party
    weapon: null,         // equipped gear id
    armour: null,
    enchants: {},         // slot -> enchantment id
    shields: 0,           // absorbed before hearts
    streak: 0,            // consecutive correct answers
    bestStreak: 0,
    stake: "safe",        // this question's stake: "safe" or "risky"
    focusUsed: false,     // Focus is once per FIGHT, reset by resetFocus()
    focusArmed: false,
    teamUpsUsed: 0,       // Team Up is limited per RUN now, not per monster
    campfiresUsed: 0,
    shardMultiplier: 1,
    shieldActive: false,  // Storm Shield blocks the next hit
    clarityActive: false, // Potion of Clarity trims the next question
    shopStock: {},        // nodeId -> generated stock, so a shop is stable
    coveredKeys: [],       // curriculum items already tested this run
    missedQs: [],          // cover keys the class got WRONG (Echoing Hall)
    eventsSeen: [],        // event ids already offered this run
    idolTaken: false,      // Whispering Idol: +50% shards, +1 wrong-answer damage
    longRoadTaken: false,
    usedQuestionIdx: [],   // avoid repeating the exact same question
    usedLuckyCharm: false,
    usedEcho: false,
    usedLastStand: false,
    lastStandsUsed: 0,    // counter: 1 base + 1 per Last Breath relic / perk
    usedLastBreath: false, // the Last Breath relic grants a second one
    startedAt: Date.now(),
    turnQueue: null,
    currentStudent: null,
    absent: [],
    encounter: null,       // active monster fight
    boss: null,
    stats: { correct: 0, wrong: 0, monsters: 0, teamups: 0 },
  };
  saveState();
  return STATE.run;
}

function currentRealm() {
  return STATE.run ? REALMS[STATE.run.realmId] : null;
}

// Remember what the class got wrong this run. The Echoing Hall event brings
// one back for a second attempt, which is spaced repetition dressed up as a
// reward - and it targets exactly the material they have demonstrably not got.
function noteMissed(q) {
  const run = STATE.run;
  if (!run || !q || !q.cover) return;
  run.missedQs = run.missedQs || [];
  // most recent last, and never more than a handful
  run.missedQs = run.missedQs.filter(k => k !== q.cover);
  run.missedQs.push(q.cover);
  if (run.missedQs.length > 12) run.missedQs.shift();
  saveState();
}

function markCovered(cover) {
  const run = STATE.run;
  if (run && cover && !run.coveredKeys.includes(cover)) {
    run.coveredKeys.push(cover);
  }
}

// Pick a question, preferring curriculum items not yet covered this run and
// avoiding exact repeats.
//
// `elite` mixes in the tier-4 bank: harder questions that ask students to USE
// the language rather than recognise it. Only Elite rooms and the Boss ever
// pass it, so an ordinary Fight stays within reach of the whole class.
function drawQuestion(realm, elite = false) {
  const run = STATE.run;
  // A run can end between a turn being scheduled and the question being drawn
  // - a party wipe mid-animation nulls STATE.run, and currentRealm() then
  // returns null. Callers pass that null straight in.
  if (!run || !realm) return null;
  const eliteBank = realm.eliteQuestions || [];
  const all = (elite && eliteBank.length && Math.random() < 0.65)
    ? eliteBank
    : realm.questions;
  const tag = i => (all === realm.questions ? i : "e" + i);
  let pool = all
    .map((q, i) => ({ q, i }))
    .filter(x => !run.usedQuestionIdx.includes(tag(x.i)));
  if (pool.length === 0) {
    run.usedQuestionIdx = run.usedQuestionIdx.filter(
      x => (all === realm.questions) !== (typeof x === "number"));
    pool = all.map((q, i) => ({ q, i }));
  }
  const fresh = pool.filter(x => !run.coveredKeys.includes(x.q.cover));
  const chosen = pick(fresh.length ? fresh : pool);
  // the used-index list is per-bank, so tag elite draws to keep them apart
  run.usedQuestionIdx.push(all === realm.questions ? chosen.i : "e" + chosen.i);
  saveState();
  return chosen.q;
}

